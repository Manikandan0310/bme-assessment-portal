/* ---------------- 3. Rank list ---------------- */
let mergedResults = [];
document.getElementById("resultsCsv").addEventListener("change", async (e) => {
  const files = Array.from(e.target.files);
  mergedResults = [];
  for (const file of files){
    const rows = parseCsv(await file.text());
    rows.forEach(r => mergedResults.push(r));
  }
  mergedResults.sort((a, b) => (Number(b.score) - Number(a.score)) || (Number(a.elapsed_seconds) - Number(b.elapsed_seconds)));
  mergedResults.forEach((r, i) => r.rank = i + 1);
  document.getElementById("resultsBadge").textContent = `${files.length} file(s), ${mergedResults.length} result(s)`;
  document.getElementById("resultsBadge").classList.add("ok");
  document.getElementById("resultsPreview").innerHTML = previewTable(mergedResults, ["rank","username","name","score","total","violations","elapsed_seconds"]);
  document.getElementById("resultsDownload").disabled = mergedResults.length === 0;
});
document.getElementById("resultsDownload").addEventListener("click", () => {
  if (!mergedResults.length) return;
  const cols = ["rank","username","name","score","total","violations","submitted_at","elapsed_seconds"];
  const csv = [cols.join(",")].concat(
    mergedResults.map(r => cols.map(c => csvCell(r[c])).join(","))
  ).join("\n");
  download("rank_list.csv", csv, "text/csv");
});
function csvCell(v){
  const s = String(v ?? "");
  return /[",\n]/.test(s) ? `"${s.replace(/"/g,'""')}"` : s;
}
